// src/application/release/installerPackager.ts — 完整安装器打包器（§10-4 完整集成）：
// 文件树 → manifest（全量 sha256 绑定）→ 生成 install.ps1（安装前全量校验，漂移即拒）→ 自研 zip 打包（确定性）
// 产物：<appName>-<version>.zip（manifest.json + install.ps1 + 业务文件）——单文件可分发、可校验、可安装
